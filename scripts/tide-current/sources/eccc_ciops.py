"""
Source collector: ECCC CIOPS coastal ocean surface currents (catalog only).

Outputs a GRIB2 source entry pointing to the rolling GitHub Release where
the actual GRIB2 files are hosted (generated by generate_ciops_gribs.py).
This collector uses only stdlib; it does NOT generate GRIB2 files or
contact the MSC Datamart.

This module is also the single source of truth for the CIOPS domain and
region metadata (DOMAINS / REGIONS below): generate_ciops_gribs.py imports
it directly (via sys.path) — same convention as sources/cmems_ibi.py and
sources/nos_ofs.py.

Background (verified live 2026-11-17):

  - Environment and Climate Change Canada (ECCC) runs three Coastal Ice
    Ocean Prediction System (CIOPS) configurations and publishes them on the
    MSC Datamart (https://dd.weather.gc.ca/): CIOPS-East (2 km, Gulf of
    Maine to Labrador incl. Gulf of St. Lawrence), CIOPS-West (2 km, BC
    coast from Washington to SE Alaska) and CIOPS-Salish Sea (500 m).
    Runs at 00/06/12/18 UTC, hourly output to +48 h; a run's files are
    complete ~7 h 10 min after its nominal time.
  - NetCDF only. GeoMet's WCS can return "application/x-grib2", but that is
    a generic GDAL encoding (discipline 0, parameter 255/255, date
    1970-01-01, one variable and one time per request) that no chart plotter
    or the plugin recognises as a current field — hence re-encoding here,
    unlike BSH whose own GRIB2 files are linked to directly.
  - The Datamart grid is MSC's interpolation of the native (rotated NEMO)
    grid onto a regular lat/lon grid. SeaWaterVelocityX/Y (vozocrtx /
    vomecrty) on that grid are true eastward/northward: the docs don't say
    so, but tidal-ellipse principal axes over 13 hourly steps line up with
    the channel axes (Juan de Fuca 106 deg, Haro Strait 160 deg, Seymour
    Narrows 168 deg, Rosario Strait 5 deg, Grand Manan Channel 39 deg, Bay
    of Fundy ~50 deg). No rotation is applied.
  - Tides are included (strongly reversing, flat tidal ellipses). Narrow
    passes are still underestimated even at 500 m (Seymour Narrows peaks at
    ~4 kn in CIOPS vs ~13-15 kn in the CHS predictions) — the CHS station
    predictions (chs_*.utcef) remain the reference inside the passes; CIOPS
    fills the area between them.
  - Licence: ECCC Data Services End-use Licence
    (https://eccc-msc.github.io/open-data/licence/readme_en/) — explicitly
    allows commercial use; requires attribution and no implied endorsement.

Region choice: NOAA SSCOFS (nos_ofs.py, 0.02 deg) already has wet data
across the Strait of Georgia, Johnstone Strait / Discovery Islands, Queen
Charlotte Strait and the west coast of Vancouver Island, and GoMOFS covers
the Bay of Fundy coarsely (0.05 deg). The CIOPS regions therefore target
what is not otherwise covered: the BC central/north coast, 500 m insets
for the Gulf Islands and Discovery Islands passes, and Atlantic Canada.
Bay of Fundy is included at CIOPS' native 2 km since it is much finer than
GoMOFS there. Sizes were estimated from measured wet-point counts x the
bytes/wet-point/hour rate of the existing IBI release files, then checked
against real output.
"""

