def file_name(domain: str, run_date: str, run_hour: str, component: str, hour: int) -> str:
    """Datamart file name for one surface velocity component ("X" or "Y")."""
    d = DOMAINS[domain]
    return (f"{run_date}T{run_hour}Z_MSC_{d['token']}_SeaWaterVelocity{component}"
            f"_DBS-0.5m_{d['grid']}_PT{hour:03d}H.nc")


def file_url(domain: str, run_date: str, run_hour: str, component: str, hour: int) -> str:
    """Dated-archive URL (stays valid across midnight, unlike /today/)."""
    d = DOMAINS[domain]
    return (f"{DATAMART_BASE}/{run_date}/WXO-DD/model_ciops/{d['path']}/{run_hour}/"
            f"{hour:03d}/{file_name(domain, run_date, run_hour, component, hour)}")


def _polygon_from_bounds(b: dict) -> dict:
    return {"type": "Polygon", "coordinates": [[
        [b["min_lon"], b["min_lat"]], [b["max_lon"], b["min_lat"]],
        [b["max_lon"], b["max_lat"]], [b["min_lon"], b["max_lat"]],
        [b["min_lon"], b["min_lat"]],
    ]]}


def _bbox_of_polygons(poly_coords: list) -> dict:
    lons = [pt[0] for poly in poly_coords for ring in poly for pt in ring]
    lats = [pt[1] for poly in poly_coords for ring in poly for pt in ring]
    return {"min_lat": min(lats) if lats else 0, "min_lon": min(lons) if lons else 0,
            "max_lat": max(lats) if lats else 0, "max_lon": max(lons) if lons else 0}


