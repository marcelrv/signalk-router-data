"""
Source collector: Rijkswaterstaat DCSM-FM 100 m forecast currents for the
Dutch Wadden Sea and the Delta (catalog only).

Outputs a GRIB2 source entry pointing to the rolling GitHub Release where
the GRIB2 files are hosted (generated by generate_dcsm_gribs.py). Stdlib
only; it does not download anything.

This module is also the single source of truth for the region metadata
(REGIONS below): generate_dcsm_gribs.py and currents_release_notes.py import
it via sys.path, same convention as cmems_nws.py.

Model: Rijkswaterstaat's operational DCSM-FM (D-Flow FM, `dflowfm2d_noordzee_100m`)
with KNMI HARMONIE wind/pressure, as published on the open NOOS Matroos server
(source `dcsm7_harmonie_bf_f2w_zuno`, database `maps2d`). Matroos serves it
interpolated to the ZUNO v4 curvilinear grid (638 x 1449), ~175-220 m cells
in the Wadden and ~70-110 m in the Delta. Velocities are depth-averaged
(east/north, m/s); land is masked, dry cells read exactly 0. Runs every 3 h
(the 00/06/12/18Z runs carry the full forecast), from analysis -3 h to +25 h.
See generate_dcsm_gribs.py for the download, time and mask quirks.

This complements, not replaces:
  - BSH North Sea GRIB (~5.5 km, surface layer): the Wadden channels are
    invisible at that resolution.
  - The tide-only DCSM UTCEF datasets (utcef_wadden_dcsm_hd /
    utcef_delta_dcsm_hd): any date, but no wind/surge.
Intended plugin order: this GRIB first (weather-aware, ~25 h ahead), then
the UTCEF, then BSH for the open sea.

The regions use the same boxes as those UTCEF datasets.

Licence: NOT yet confirmed for the Matroos model output. PUBLISH_TO_CATALOG
stays False (and the workflow does not upload) until it is.
"""

import json
import sys

# Gate for the catalog entry. Off until the Rijkswaterstaat / Matroos data
# licence is confirmed: the index must not point at a release that does not
# exist (the workflow's upload is gated by the same decision).
PUBLISH_TO_CATALOG = False

GITHUB_RELEASE_BASE = "https://github.com/marcelrv/signalk-router-data/releases/download/dcsm-currents-latest"

MATROOS_BASE = "https://noos.matroos.rws.nl/direct"
MATROOS_DATABASE = "maps2d"
MATROOS_SOURCE = "dcsm7_harmonie_bf_f2w_zuno"

# Analysis hours the pipeline is allowed to pick (the workflow passes the
# one it wants). The 00Z run is on Matroos around 04:15 UTC, the 12Z run
# around 16:15 UTC.
CYCLES = ["00", "12"]

# Output grid: ~240 m E-W x ~280 m N-S at 52-53.5N. The source is ~200 m in
# the Wadden and ~70-110 m in the Delta, so this keeps the channels while
# holding a 26-step file per region well under ~40 MB.
TARGET_RES_LAT_DEG = 0.0025
TARGET_RES_LON_DEG = 0.0035

REGIONS = {
    "dcsm_wadden": {
        "name": "Dutch Wadden Sea (DCSM-FM)",
        "description": "Forecast currents (tide + weather) for the Dutch Wadden Sea from Den "
                       "Helder to the Eems/Dollard, including the tidal inlets and ~20 km of "
                       "North Sea off the islands.",
        "bounds": {"min_lat": 52.88, "max_lat": 53.72, "min_lon": 4.55, "max_lon": 7.35},
        "target_res_lat_deg": TARGET_RES_LAT_DEG,
        "target_res_lon_deg": TARGET_RES_LON_DEG,
        "forecast_hours": 25,
    },
    "dcsm_delta": {
        "name": "Dutch Delta (DCSM-FM)",
        "description": "Forecast currents (tide + weather) for the Voordelta, Westerschelde "
                       "(to Antwerp), Oosterschelde, Haringvliet/Slijkgat and the Maasmond.",
        "bounds": {"min_lat": 51.20, "max_lat": 52.05, "min_lon": 3.00, "max_lon": 4.42},
        "target_res_lat_deg": TARGET_RES_LAT_DEG,
        "target_res_lon_deg": TARGET_RES_LON_DEG,
        "forecast_hours": 25,
    },
}

DESCRIPTION = (
    "High-resolution (~250 m) forecast currents (tide + wind + surge, depth-averaged) for "
    "the Dutch Wadden Sea and the Delta, from Rijkswaterstaat's operational DCSM-FM 100 m "
    "model as published on the open NOOS Matroos server, regridded to a regular lat/lon "
    "grid and re-encoded as GRIB2 by signalk-router-data scripts "
    "(https://github.com/marcelrv/signalk-router-data). Hourly, from the model analysis "
    "to +25 h. Depth-averaged, so speeds are ~20% below surface-current models such as "
    "BSH. Source: Rijkswaterstaat (DCSM-FM, NOOS Matroos). This repackaging is NOT an "
    "official Rijkswaterstaat product and is not endorsed by Rijkswaterstaat. "
    "LICENCE NOT YET CONFIRMED: test use only. Not for navigation."
)


def _polygon_from_bounds(b: dict) -> dict:
    return {"type": "Polygon", "coordinates": [[
        [b["min_lon"], b["min_lat"]], [b["max_lon"], b["min_lat"]],
        [b["max_lon"], b["max_lat"]], [b["min_lon"], b["max_lat"]],
        [b["min_lon"], b["min_lat"]],
    ]]}


def _bbox_of_polygons(poly_coords: list) -> dict:
    lons = [pt[0] for poly in poly_coords for ring in poly for pt in ring]
    lats = [pt[1] for poly in poly_coords for ring in poly for pt in ring]
    return {"min_lat": min(lats), "min_lon": min(lons),
            "max_lat": max(lats), "max_lon": max(lons)}


def build_source() -> dict:
    all_poly_coords = []
    files_entries = []
    for rid, r in REGIONS.items():
        poly = _polygon_from_bounds(r["bounds"])
        all_poly_coords.append(poly["coordinates"])
        files_entries.append({
            "region_id": rid,
            "name": r["name"],
            "description": r["description"],
            "boundary_geometry": poly,
            "type": "forecast",
            "url_template": f"{GITHUB_RELEASE_BASE}/{rid}_currents.grb2",
            # One multi-message file per region (all hours), same as
            # cmems_nws.py.
            "forecast_hours": [0],
            # When the release asset is refreshed: ~05 UTC from the 00Z run,
            # ~17 UTC from the 12Z run.
            "cycle_hours": ["05", "17"],
        })

    return {
        "id": "rws_dcsm",
        "source": "rws",
        "type": "grib2",
        "name": "Forecast Currents — Dutch Wadden Sea & Delta (Rijkswaterstaat DCSM-FM, TEST)",
        "description": DESCRIPTION,
        "contributor": "Rijkswaterstaat (DCSM-FM via NOOS Matroos)",
        "url": "https://noos.matroos.rws.nl/",
        "tags": ["grib2", "regional", "gridded", "forecast", "rws", "dcsm-fm",
                 "ocean-currents", "high-density", "test", "europe", "netherlands"],
        "region": {
            "name": "Netherlands — Wadden Sea & Delta",
            "bounding_box": _bbox_of_polygons(all_poly_coords),
            "boundary_geometry": {"type": "MultiPolygon", "coordinates": all_poly_coords},
        },
        # 00Z and 12Z runs, so a file is never more than ~12 h old when the
        # pipeline is healthy.
        "update_check": {"method": "expiry", "max_age_hours": 12, "last_checked": ""},
        "files": files_entries,
    }


def main() -> None:
    if not PUBLISH_TO_CATALOG and "--force" not in sys.argv:
        json.dump([], sys.stdout)
        print()
        return
    json.dump(build_source(), sys.stdout, indent=2)
    print()


if __name__ == "__main__":
    main()
