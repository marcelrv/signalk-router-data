"""
Source collector: NOAA NOS Operational Forecast Systems (OFS) Surface Currents (catalog only).

Outputs a GRIB2 source entry pointing to the rolling GitHub Release where
the actual GRIB2 files are hosted (generated by generate_ofs_gribs.py).
This collector uses only stdlib; it does NOT generate GRIB2 files or
contact real-time data servers.

This module is also the single source of truth for the NOS OFS model
metadata (MODELS below): generate_ofs_gribs.py imports it directly (via
sys.path, since it lives in a sibling directory) rather than keeping a
second, drifting copy. Keep this module stdlib-only — the weekly index
generator runs it without the heavy netCDF/eccodes dependencies that
generate_ofs_gribs.py requires.

Model cycles, forecast horizons, and bounds below were verified live
against the THREDDS catalog (opendap.co-ops.nos.noaa.gov) on 2026-07-14:
grid corner coordinates were fetched via the DAP .ascii endpoint and
bounds set from them (rounded outward to ~0.1 degree). In particular:
  - SSCOFS = Salish Sea & Columbia River OFS, NOT "Southern California".
    Confirmed grid corners: 44.37N/-129.53E to 52.13N/-121.94E.
  - NGOFS2's grid actually starts near 21.8N (not the previously assumed
    25N). Confirmed grid corners: 21.77N/-97.88E to 30.80N/-85.72E.
  - WCOFS's regulargrid domain spans a much larger area than its name
    suggests (18.42N-55.78N, -145.38E to -112.10E) and is 3-hourly.
"""

import json
import sys

