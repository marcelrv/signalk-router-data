def _polygon_from_bounds(b: dict) -> dict:
    return {"type": "Polygon", "coordinates": [[
        [b["min_lon"], b["min_lat"]], [b["max_lon"], b["min_lat"]],
        [b["max_lon"], b["max_lat"]], [b["min_lon"], b["max_lat"]],
        [b["min_lon"], b["min_lat"]],
    ]]}


def _bbox_of_polygons(poly_coords: list) -> dict:
    lons = [pt[0] for poly in poly_coords for ring in poly for pt in ring]
    lats = [pt[1] for poly in poly_coords for ring in poly for pt in ring]
    return {"min_lat": min(lats) if lats else 0, "min_lon": min(lons) if lons else 0,
            "max_lat": max(lats) if lats else 0, "max_lon": max(lons) if lons else 0}


def main() -> None:
    if not PUBLISH_TO_CATALOG:
        json.dump([], sys.stdout)
        print()
        return

    all_poly_coords = []
    files_entries = []

    for mid, m in MODELS.items():
        b = m["bounds"]
        poly = _polygon_from_bounds(b)
        all_poly_coords.append(poly["coordinates"])
        files_entries.append({
            "region_id": mid,
            "name": m["name"],
            "description": m["description"],
            "boundary_geometry": poly,
            "type": "forecast",
            "url_template": f"{GITHUB_RELEASE_BASE}/{mid}_currents.grb2",
            # Each GRIB2 file bundles every forecast hour as separate
            # messages (no {hour:03d} placeholder in url_template above) —
            # a single-element array signals "one file, not one per hour"
            # (see specs/tide-current-catalog.md §3.3 and the BSH nowcast
            # entries in bsh_currents.py for the same convention).
            "forecast_hours": [0],
            "cycle_hours": m["cycles"],
        })

    source = {
        "id": "nos_ofs",
        "source": "noaa",
        "type": "grib2",
        "name": "Surface Current Forecasts — US Waters (NOAA OFS)",
        "description": "Gridded surface current forecasts (tidal + weather + river forcing) for "
                       "US waters, extracted and re-encoded from official NOAA NOS Operational "
                       "Forecast System model guidance by signalk-router-data scripts "
                       "(https://github.com/marcelrv/signalk-router-data). NOAA data is public "
                       "domain (U.S. Government work); this repackaging is NOT an official NOAA "
                       "product and is not endorsed by NOAA.",
        "contributor": "NOAA National Ocean Service (NOS)",
        "url": "https://tidesandcurrents.noaa.gov/ofs/",
        "tags": ["grib2", "regional", "gridded", "forecast", "noaa", "ocean-currents", "daily"],
        "region": {
            "name": "U.S. Coastal Waters",
            "bounding_box": _bbox_of_polygons(all_poly_coords) if all_poly_coords else {},
            "boundary_geometry": {"type": "MultiPolygon", "coordinates": all_poly_coords},
        },
        "update_check": {"method": "expiry", "max_age_hours": 24, "last_checked": ""},
        "files": files_entries,
    }

    json.dump(source, sys.stdout, indent=2)
    print()


if __name__ == "__main__":
    main()
