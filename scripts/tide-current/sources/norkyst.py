"""
Source collector: MET Norway NorKyst v3 (800 m) surface currents (catalog only).

Outputs a GRIB2 source entry pointing to the rolling GitHub Release where
the actual GRIB2 files are hosted (generated by generate_norkyst_gribs.py).
This collector uses only stdlib; it does NOT generate GRIB2 files or
contact the MET Norway THREDDS server.

This module is also the single source of truth for the NorKyst region
metadata (REGIONS below): generate_norkyst_gribs.py imports it directly (via
sys.path, since it lives in a sibling directory) rather than keeping a
second, drifting copy — same convention as sources/cmems_ibi.py.

Issue #5. Source facts (checked on the live server, Nov 2026):
  - Dataset: OPeNDAP fou-hi/norkystv3_800m_m00_be on thredds.met.no, the
    NorKyst v3 ROMS model, 800 m, polar-stereographic grid. Surface
    u_eastward / v_northward.
  - One run per day at 00 UTC, hourly to +120 h; we publish 72 h.
  - No credentials needed.
  - Licence CC-BY-4.0, "Norwegian Meteorological Institute (MET Norway)"
    (https://www.met.no/en/free-meteorological-data/Licensing-and-crediting).
  - Replaces the legacy norkyst800m-1h product, which stopped on 2025-10-05.
  - The forecast reaches THREDDS in five parts, the last around 06:15 UTC;
    until then the aggregation shows an incomplete run (hence the 06:50 cron).
  - Limitation: straits narrower than the 800 m grid are land in the model
    (Saltstraumen, Rystraumen: no wet cell), so they carry no current here.
    Wider tidal streams are resolved (Moskstraumen peaks ~1.8 m/s).

Sizing: the model is regridded to a regular lat/lon grid and encoded at 12
bits per value (see sources/rws_dcsm.py for the packing reasoning). Open sea
farther than offshore_km from land is left out (bitmap missing) to keep the
files at or under about 10 MB; the fjords, the skerries and the coastal
waters a boat sails in are kept. Measured cost: about 3.0 B per wet point per
step at 12 bits, plus a 0.25 B per grid cell per step bitmap. Estimated 72 h
file sizes: norkyst_south ~9.5 MB, norkyst_west ~9 MB, norkyst_nordland
~7.6 MB, norkyst_north ~7.8 MB. The regions are separate downloads so a sailor
fetches only the stretch of coast they sail; they overlap at the seams so a
route never falls into a gap.
"""

